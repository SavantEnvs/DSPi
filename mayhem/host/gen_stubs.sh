#!/usr/bin/env bash
# gen_stubs.sh OUT.c OBJ... — emit a no-op definition for every symbol the
# objects reference but nothing defines (Pico SDK hardware calls, and globals
# of the audio-I/O files the host build leaves out).  A symbol referenced
# through a PLT/call relocation becomes `long f(void) { return 0; }`; any
# other becomes a zeroed 16 KiB, 64-byte-aligned array.
set -euo pipefail
out=$1; shift
tmp=$(mktemp -d)
nm -u "$@" 2>/dev/null | awk 'NF==2 && $1=="U"{print $2} NF==1{print $1}' | grep -v ':$' | sort -u > "$tmp/undef"
nm --defined-only "$@" 2>/dev/null | awk 'NF>=3{print $3}' | sort -u > "$tmp/def"
comm -23 "$tmp/undef" "$tmp/def" \
  | grep -Ev '^(__asan|__ubsan|__sanitizer|__sancov|__start_|__stop_|__dspi_state|_GLOBAL_OFFSET_TABLE_|__dso_handle|__tls_get_addr|_Unwind|__cxa|__gxx|__stack_chk)' > "$tmp/missing"
# keep only names libc/libm do not provide
libdir=$(dirname "$(${CC:-clang} -print-file-name=libc.so.6)")
nm -D --defined-only "$libdir/libc.so.6" "$libdir/libm.so.6" 2>/dev/null | awk 'NF>=3{sub(/@.*/,"",$3); print $3}' | sort -u > "$tmp/libc"
comm -23 "$tmp/missing" "$tmp/libc" > "$tmp/need"
for o in "$@"; do readelf -rW "$o" 2>/dev/null; done | awk '$3 ~ /PLT32|GOTPCREL/ || $3 ~ /PC32/ {print $3, $5}' > "$tmp/relocs"
# A `long f(void)` stub is only ABI-safe for integer/pointer/void returns: a float or double
# result comes back in xmm0, which the stub never writes, so the caller would read garbage.
# Refuse to guess -- such a function needs a typed stub in sdk_stubs.c.
root=$(cd "$(dirname "$0")/../.." && pwd)
bad=""
while read -r s; do
  grep -q "R_X86_64_PLT32 $s\$" "$tmp/relocs" || continue
  if grep -rEq --include='*.h' --include='*.c' \
       "(^|[^[:alnum:]_])(float|double)[[:space:]]+$s[[:space:]]*\(" \
       "$root/firmware/DSPi" "$root/mayhem/host/include" "$root/firmware/pico-extras/src" 2>/dev/null; then
    bad="$bad $s"
  fi
done < "$tmp/need"
if [ -n "$bad" ]; then
  echo "gen_stubs.sh: floating-point-returning functions need a typed stub in mayhem/host/sdk_stubs.c:$bad" >&2
  rm -rf "$tmp"; exit 1
fi
{
  echo "/* generated by mayhem/host/gen_stubs.sh — do not edit */"
  echo "#include <stdint.h>"
  echo '#pragma clang section bss=".bss.dspi_state" data=".data.dspi_state"'
  while read -r s; do
    if grep -q "R_X86_64_PLT32 $s\$" "$tmp/relocs"; then
      echo "long $s(void) { return 0; }"
    else
      echo "__attribute__((aligned(64))) unsigned char $s[16384];"
    fi
  done < "$tmp/need"
} > "$out"
rm -rf "$tmp"
